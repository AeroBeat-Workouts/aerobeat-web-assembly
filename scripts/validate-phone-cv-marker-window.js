assert.equal(report.displayWeightedPoseAgeMs.p50,20);
assert.equal(report.camera.configuredFrameRateFps,30);
assert.doesNotMatch(JSON.stringify(report),/sceneFrames|deviceId|mediaTime|landmarks|coordinates|sourceId|songId|poseX|image|pixels/i);
