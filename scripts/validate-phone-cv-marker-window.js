window.pose({poseFrameCount:5},1300,18,25,true,false,true);
window.display(1320,true);window.display(1340,true);
const report=window.stop(61000,status);
assert.equal(report.valid,true);assert.equal(report.durationMs,60000);
assert.deepEqual(report.counts,{cameraUniqueMediaFrames:2,cvSubmitted:6,cvPoses:2,cvBusyDrops:2,nativeFreshInput:2,freshValidMarkers:1,freshHeldMarkers:1,markerPresentationFrames:2});
